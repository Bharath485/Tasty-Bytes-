{{
    config(
        materialized='incremental',
        incremental_strategy='merge',
        unique_key='ORDER_ID',
        alias='FACT_ORDER',
        tags=['cortex_generated', 'fact']
    )
}}

with order_header as (

    select
        order_id,
        order_ts
    from {{ source('raw', 'ORDER_HEADER') }}
    {% if is_incremental() %}
    where order_ts > (select coalesce(max(ORDER_TIMESTAMP), '1900-01-01'::timestamp) from {{ this }})
    {% endif %}

),

order_detail_agg as (

    select
        order_id,
        sum(price)    as total_line_amount,
        sum(quantity) as total_quantity
    from {{ source('raw', 'ORDER_DETAIL') }}
    group by order_id

)

select
    cast(h.order_id as integer)                             as ORDER_ID,
    cast(h.order_ts as timestamp)                           as ORDER_TIMESTAMP,
    cast(coalesce(d.total_line_amount, 0) as numeric(38, 4)) as TOTAL_LINE_AMOUNT,
    cast(coalesce(d.total_quantity, 0) as integer)          as TOTAL_QUANTITY
from order_header h
left outer join order_detail_agg d
    on h.order_id = d.order_id
