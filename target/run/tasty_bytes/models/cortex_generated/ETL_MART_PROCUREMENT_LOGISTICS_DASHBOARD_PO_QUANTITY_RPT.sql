-- Step 1 Batch process info




WITH PO_LINE_LOCATION_DIM AS (
    SELECT 
        LINE_LOCATION_ID,
        PO_HEADER_ID,
        PO_LINE_ID,
        SHIPMENT_NUM,
        SCHEDULE_STATUS,
        PROMISED_DATE,
        NEED_BY_DATE,
        CREATION_DATE,
        RECEIPT_REQUIRED_FLAG,
        INSPECTION_REQUIRED_FLAG
    FROM DBT_POC.DEV.MART_PROCUREMENT_PO_LINE_LOCATION_DIM
    WHERE 
        
                BIW_UPD_DTTM >= '2020-01-01 00:00:00.000' 
            AND BIW_UPD_DTTM <= '2099-12-31 23:59:59.999'
            
)

,PO_HEADER_DIM AS (
    SELECT 
        PO_HEADER_ID,
        SEGMENT1,
        APPROVED_DATE,
        ATTRIBUTE7,
        CURRENCY_CODE,
        AUTHORIZATION_STATUS,
        AGENT_ID
    FROM DBT_POC.DEV.MART_PROCUREMENT_PO_HEADER_DIM
)

,PO_LINE_DIM AS (
    SELECT 
        PO_LINE_ID,
        PO_HEADER_ID,
        LINE_NUM,
        ITEM_DESCRIPTION,
        VENDOR_PRODUCT_NUM,
        UOM_CODE
    FROM DBT_POC.DEV.MART_PROCUREMENT_PO_LINE_DIM
)

,PO_RELEASE_FACT AS (
    SELECT 
        PO_RELEASE_ID,
        PO_HEADER_ID,
        RELEASE_NUM,
        AUTHORIZATION_STATUS
    FROM DBT_POC.DEV.MART_PROCUREMENT_PO_RELEASE_FACT
)

,SUPPLIER_DIM AS (
    SELECT 
        VENDOR_ID,
        SUPPLIER_NAME
    FROM DBT_POC.DEV.MART_PROCUREMENT_SUPPLIER_DIM
)

,SUPPLIER_SITE_DIM AS (
    SELECT 
        VENDOR_SITE_ID,
        SUPPLIER_SITE_CODE
    FROM DBT_POC.DEV.MART_PROCUREMENT_SUPPLIER_SITE_DIM
)

,PDH_ITEM_ORGANIZATION_DIM AS (
    SELECT 
        INVENTORY_ITEM_ID,
        ORGANIZATION_ID,
        ITEM_NUMBER,
        PLANNER_CODE
    FROM DBT_POC.DEV.MART_PDM_PDH_ITEM_ORGANIZATION_DIM
)

,HR_LOCATIONS_ALL AS (
    SELECT 
        LOCATION_ID,
        LOCATION_CODE
    FROM DBT_POC.DEV.ODS_HCM_SHARED_HR_LOCATIONS_ALL
)

,PERSON_DIM AS (
    SELECT 
        PERSON_ID,
        FULL_NAME
    FROM DBT_POC.DEV.MART_PROCUREMENT_PERSON_DIM
)

,HR_ORGANIZATION_UNITS AS (
    SELECT 
        ORGANIZATION_ID,
        NAME
    FROM DBT_POC.DEV.ODS_HCM_SHARED_HR_ORGANIZATION_UNITS
)

,PO_LINE_LOCATION_CURR_FACT AS (
    SELECT 
        LINE_LOCATION_ID,
        QUANTITY,
        QUANTITY_RECEIVED,
        QUANTITY_BILLED,
        QUANTITY_CANCELLED,
        PRICE_OVERRIDE
    FROM DBT_POC.DEV.MART_PROCUREMENT_PO_LINE_LOCATION_CURR_FACT
)



SELECT 
    -- Primary Key
    MD5(OBJECT_CONSTRUCT(
        'COL1', PLL.PO_HEADER_ID::STRING,
        'COL2', PLL.PO_LINE_ID::STRING,
        'COL3', PLL.LINE_LOCATION_ID::STRING
    )::STRING)::STRING AS LOGISTICS_DASHBOARD_PO_QUANTITY_KEY,
    
    -- Natural Keys
    POH.PO_HEADER_ID,
    POL.PO_LINE_ID,
    PLL.LINE_LOCATION_ID,
    
    -- Business Columns
    POH.SEGMENT1 || CASE WHEN PRA.RELEASE_NUM IS NOT NULL THEN '-' ELSE '' END || PRA.RELEASE_NUM AS PO_NUMBER,
    POL.LINE_NUM,
    POL.LINE_NUM AS PO_LINE_NUMBER,
    PLL.SHIPMENT_NUM AS SHIPMENT_NUMBER,
    POH.SEGMENT1 || '-' || POL.LINE_NUM || '-' || PLL.SHIPMENT_NUM AS PO_NUM_LINE_SHIP,
    NVL(PLL.SCHEDULE_STATUS, 'OPEN') AS STATUS,
    SUP.SUPPLIER_NAME AS SUPPLIER,
    SS.SUPPLIER_SITE_CODE AS SUPPLIER_SITE,
    ITM.ITEM_NUMBER AS ITEM_NUM,
    POL.ITEM_DESCRIPTION,
    POL.VENDOR_PRODUCT_NUM AS SUPPLIER_ITEM_NUM,
    NVL(PLL.PROMISED_DATE, PLL.NEED_BY_DATE) AS DUE_DATE,
    PLL.PROMISED_DATE,
    PLL.CREATION_DATE AS LINE_CREATION_DATE,
    POH.APPROVED_DATE AS PO_APPROVED_DATE,
    POH.ATTRIBUTE7 AS PO_TYPE,
    POH.CURRENCY_CODE,
    POL.UOM_CODE AS UNIT_MEAS_LOOKUP_CODE,
    LOC.LOCATION_CODE AS SHIP_TO_LOCATION,
    DECODE(PLL.PO_LINE_ID, NULL, NVL(POH.AUTHORIZATION_STATUS, 'INCOMPLETE'),
        NVL(PRA.AUTHORIZATION_STATUS, 'INCOMPLETE')) AS AUTHORIZATION_STATUS,
    DECODE(PLL.RECEIPT_REQUIRED_FLAG,
        'N',
        DECODE(PLL.INSPECTION_REQUIRED_FLAG,
                'N',
                '2-Way',
                NULL), 'Y',
                       DECODE(PLL.INSPECTION_REQUIRED_FLAG,
                               'N',
                               '3-Way',
                               'Y',
                               '4-Way',
                               NULL)) AS MATCHING_TYPE,
    CASE
        WHEN DATEDIFF(DAY, PLL.NEED_BY_DATE, CURRENT_DATE) BETWEEN 1 AND 29 THEN '1-30_PASTDUE'
        WHEN DATEDIFF(DAY, PLL.NEED_BY_DATE, CURRENT_DATE) BETWEEN 30 AND 59 THEN '30-60_PASTDUE'
        WHEN DATEDIFF(DAY, PLL.NEED_BY_DATE, CURRENT_DATE) BETWEEN 60 AND 89 THEN '60-90_PASTDUE'
        WHEN DATEDIFF(DAY, PLL.NEED_BY_DATE, CURRENT_DATE) >= 90 THEN '90_PASTDUE'
        ELSE NULL
    END AS PAST_DUE,
    PER.FULL_NAME AS BUYER,
    ITM.PLANNER_CODE,
    ORG.NAME,
    PLLF.QUANTITY - PLLF.QUANTITY_RECEIVED AS QUANTITY_DUE,
    PLLF.QUANTITY AS QUANTITY_ORDERED,
    PLLF.QUANTITY_RECEIVED,
    PLLF.QUANTITY_BILLED,
    PLLF.QUANTITY_CANCELLED,
    PLLF.PRICE_OVERRIDE * (PLLF.QUANTITY - NVL(PLLF.QUANTITY_CANCELLED, 0)) AS SHIPMENT_AMOUNT,
    
    -- Housekeeping Columns
    'N'::BOOLEAN AS IS_DELETE,
    '2026-03-10 13:56:18.000'::TIMESTAMP_NTZ AS BIW_INS_DTTM,
    '2026-03-10 13:56:18.000'::TIMESTAMP_NTZ AS BIW_UPD_DTTM,
    '1'::NUMBER(38,0) AS BIW_BATCH_ID,
    MD5(OBJECT_CONSTRUCT(
        'COL1', PLL.PO_HEADER_ID::STRING,
        'COL2', POL.PO_LINE_ID::STRING,
        'COL3', PLL.LINE_LOCATION_ID::STRING,
        'COL4', POH.SEGMENT1::STRING,
        'COL5', POL.LINE_NUM::STRING,
        'COL6', PLL.SHIPMENT_NUM::STRING,
        'COL7', NVL(PLL.SCHEDULE_STATUS, 'OPEN')::STRING,
        'COL8', SUP.SUPPLIER_NAME::STRING,
        'COL9', SS.SUPPLIER_SITE_CODE::STRING,
        'COL10', ITM.ITEM_NUMBER::STRING,
        'COL11', POL.ITEM_DESCRIPTION::STRING,
        'COL12', POL.VENDOR_PRODUCT_NUM::STRING,
        'COL13', NVL(PLL.PROMISED_DATE, PLL.NEED_BY_DATE)::STRING,
        'COL14', PLL.PROMISED_DATE::STRING,
        'COL15', PLL.CREATION_DATE::STRING,
        'COL16', POH.APPROVED_DATE::STRING,
        'COL17', POH.ATTRIBUTE7::STRING,
        'COL18', POH.CURRENCY_CODE::STRING,
        'COL19', POL.UOM_CODE::STRING,
        'COL20', LOC.LOCATION_CODE::STRING,
        'COL21', POH.AUTHORIZATION_STATUS::STRING,
        'COL22', PLL.RECEIPT_REQUIRED_FLAG::STRING,
        'COL23', PLL.INSPECTION_REQUIRED_FLAG::STRING,
        'COL24', PLL.NEED_BY_DATE::STRING,
        'COL25', PER.FULL_NAME::STRING,
        'COL26', ITM.PLANNER_CODE::STRING,
        'COL27', ORG.NAME::STRING,
        'COL28', PLLF.QUANTITY::STRING,
        'COL29', PLLF.QUANTITY_RECEIVED::STRING,
        'COL30', PLLF.QUANTITY_BILLED::STRING,
        'COL31', PLLF.QUANTITY_CANCELLED::STRING,
        'COL32', PLLF.PRICE_OVERRIDE::STRING,
        'COL33', PRA.RELEASE_NUM::STRING,
        'COL34', PRA.AUTHORIZATION_STATUS::STRING
    )::STRING)::BINARY AS BIW_MD5_KEY

FROM PO_LINE_LOCATION_DIM PLL
LEFT OUTER JOIN PO_HEADER_DIM POH
    ON PLL.PO_HEADER_ID = POH.PO_HEADER_ID
LEFT OUTER JOIN PO_LINE_DIM POL
    ON PLL.PO_LINE_ID = POL.PO_LINE_ID
LEFT OUTER JOIN PO_RELEASE_FACT PRA
    ON PLL.PO_HEADER_ID = PRA.PO_HEADER_ID
LEFT OUTER JOIN SUPPLIER_DIM SUP
    ON POH.PO_HEADER_ID = SUP.VENDOR_ID
LEFT OUTER JOIN SUPPLIER_SITE_DIM SS
    ON POH.PO_HEADER_ID = SS.VENDOR_SITE_ID
LEFT OUTER JOIN PDH_ITEM_ORGANIZATION_DIM ITM
    ON POL.PO_LINE_ID = ITM.INVENTORY_ITEM_ID
LEFT OUTER JOIN HR_LOCATIONS_ALL LOC
    ON PLL.LINE_LOCATION_ID = LOC.LOCATION_ID
LEFT OUTER JOIN PERSON_DIM PER
    ON POH.AGENT_ID = PER.PERSON_ID
LEFT OUTER JOIN HR_ORGANIZATION_UNITS ORG
    ON ITM.ORGANIZATION_ID = ORG.ORGANIZATION_ID
LEFT OUTER JOIN PO_LINE_LOCATION_CURR_FACT PLLF
    ON PLL.LINE_LOCATION_ID = PLLF.LINE_LOCATION_ID
    )
;


  